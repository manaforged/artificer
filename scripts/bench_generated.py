import os
import shutil
import subprocess
import time
from bench_support import (
    EXE,
    check_counters,
    driver_env,
    nextest_bin,
    read_counters,
    run,
    run_tests,
    store_delta,
    timed,
)


TEST_MS = 200


def fold(base):
    """Mirror of the generated crate's fold(), for the output check."""
    mask = (1 << 64) - 1
    return sum(n * (base | 1) for n in range(64) if n % 3 == 0) & mask


def expected_output(mid_index, top_index, mid_base):
    """The binary prints the mid crate's BASE and the folded work."""
    total = (fold(mid_base) + fold(top_index)) & ((1 << 64) - 1)
    return f"{mid_base} {total}"


def crate_source(index):
    """One generated crate. Keeps a real dependency edge and some
    iterator work, so rustc does more than start up."""
    deps = ""
    body = "    let mut total = BASE + 1;\n"
    if index >= 1:
        deps += f'c{index - 1} = {{ path = "../c{index - 1}" }}\n'
        body += f"    total = total.wrapping_add(c{index - 1}::value());\n"
    if index >= 2:
        deps += f'c{index - 2} = {{ path = "../c{index - 2}" }}\n'
        body += f"    total = total.wrapping_add(c{index - 2}::value());\n"
    manifest = f"""[package]
name = "c{index}"
version = "0.1.0"
edition = "2021"

[dependencies]
{deps}"""
    source = f"""//! Generated by scripts/bench.py.
pub const BASE: u64 = {index};

pub fn value() -> u64 {{
{body}    total
}}

pub fn fold() -> u64 {{
    (0..64u64)
        .filter(|n| n % 3 == 0)
        .map(|n| n.wrapping_mul(BASE | 1))
        .sum()
}}
"""
    return manifest, source


def write_workspace(root, crates):
    """Generate the workspace. Returns the edited crate's name and its
    initial constant, so the harness knows the expected output."""
    members = []
    for index in range(crates):
        d = root / "crates" / f"c{index}"
        (d / "src").mkdir(parents=True)
        manifest, source = crate_source(index)
        (d / "Cargo.toml").write_text(manifest)
        (d / "src/lib.rs").write_text(source)
        tests = d / "tests"
        tests.mkdir()
        (tests / "t.rs").write_text(
            "#[test]\n"
            "fn t() {\n"
            f"    std::thread::sleep(std::time::Duration::from_millis({TEST_MS}));\n"
            f"    assert_eq!(c{index}::BASE, {index});\n"
            "}\n"
        )
        members.append(f'"crates/c{index}"')

    mid = crates // 2
    top = crates - 1
    app = root / "apps" / "bench-app"
    (app / "src").mkdir(parents=True)
    (app / "Cargo.toml").write_text(f"""[package]
name = "bench-app"
version = "0.1.0"
edition = "2021"

[dependencies]
c{mid} = {{ path = "../../crates/c{mid}" }}
c{top} = {{ path = "../../crates/c{top}" }}
""")
    (app / "src/main.rs").write_text(
        "fn main() {\n"
        f"    let folded = c{mid}::fold().wrapping_add(c{top}::fold());\n"
        f'    println!("{{}} {{}}", c{mid}::BASE, folded);\n'
        "}\n"
    )
    members.append('"apps/bench-app"')
    (root / "Cargo.toml").write_text(
        "[workspace]\nresolver = \"2\"\nmembers = [\n    "
        + ",\n    ".join(members)
        + ",\n]\n"
    )
    return f"c{mid}", mid, top


def build_command(driver, stock, target, store):
    return [driver, "build"], driver_env(driver, stock, target, store)


def build_and_check(driver, checkout, target, store, stock, expected):
    """One measured build plus the output equality check."""
    cmd, env = build_command(driver, stock, target, store)
    seconds = timed(cmd, checkout, env)
    app = target / "debug" / f"bench-app{EXE}"
    if not app.is_file():
        raise SystemExit(f"{driver} did not deliver {app}")
    done = run([app], checkout, dict(os.environ))
    got = done.stdout.strip()
    if got != str(expected):
        raise SystemExit(
            f"output check failed: {app} printed {got!r}, expected {expected!r}"
        )
    return seconds


def measure(driver, stock, workspace_root, samples, crates, keep):
    """Run the four cases for one driver, once per sample. Each sample
    gets a fresh store, or its second cold run would be warm."""
    times = {
        "cold": [],
        "noop": [],
        "second-checkout": [],
        "parallel": [],
        "check": [],
        "test": [],
        "test-warm": [],
        "nextest": [],
        "nextest-warm": [],
        "edit": [],
    }
    nextest = nextest_bin()
    for sample in range(samples):
        work = workspace_root / f"sample-{sample}"
        shutil.rmtree(work, ignore_errors=True)
        checkout_a = work / "checkout-a"
        checkout_a.mkdir(parents=True)
        mid_name, mid, top = write_workspace(checkout_a, crates)
        run(
            [stock, "generate-lockfile", "--manifest-path", checkout_a / "Cargo.toml"],
            checkout_a,
            dict(os.environ),
        )
        target_a = work / "target-a"
        target_b = work / "target-b"
        driver_store = work / "store"
        driver_store.mkdir()

        is_artificer = driver != stock
        before = read_counters(driver_store)
        times["cold"].append(
            build_and_check(
                driver,
                checkout_a,
                target_a,
                driver_store,
                stock,
                expected_output(mid, top, mid),
            )
        )
        check_counters(is_artificer, "cold", before, read_counters(driver_store))

        before = read_counters(driver_store)
        times["noop"].append(
            build_and_check(
                driver,
                checkout_a,
                target_a,
                driver_store,
                stock,
                expected_output(mid, top, mid),
            )
        )
        check_counters(is_artificer, "noop", before, read_counters(driver_store))

        checkout_b = work / "checkout-b"
        shutil.copytree(checkout_a, checkout_b)
        before = read_counters(driver_store)
        times["second-checkout"].append(
            build_and_check(
                driver,
                checkout_b,
                target_b,
                driver_store,
                stock,
                expected_output(mid, top, mid),
            )
        )
        check_counters(is_artificer, "second-checkout", before, read_counters(driver_store))

        parallel = []
        for slot in range(4):
            checkout = work / f"parallel-{slot}"
            shutil.copytree(checkout_b, checkout)
            target = work / f"parallel-target-{slot}"
            cmd, env = build_command(driver, stock, target, driver_store)
            parallel.append((checkout, target, cmd, env))
        before = read_counters(driver_store)
        start = time.perf_counter()
        running = [
            (
                entry,
                subprocess.Popen(
                    [str(c) for c in entry[2]],
                    cwd=str(entry[0]),
                    env=entry[3],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                ),
            )
            for entry in parallel
        ]
        for entry, proc in running:
            _, err = proc.communicate(timeout=1800)
            if proc.returncode != 0:
                raise SystemExit(f"parallel build failed:\n{err[-2000:]}")
        times["parallel"].append(time.perf_counter() - start)
        for checkout, target, _, _ in parallel:
            app = target / "debug" / f"bench-app{EXE}"
            done = run([app], checkout, dict(os.environ))
            if done.stdout.strip() != expected_output(mid, top, mid):
                raise SystemExit(f"parallel output check failed in {checkout}")
        if is_artificer:
            _, misses = store_delta("parallel", before, read_counters(driver_store))
            if misses > crates + 2:
                raise SystemExit(
                    f"parallel: {misses} unit misses for {crates} crates;"
                    " identical work was not deduplicated"
                )

        before = read_counters(driver_store)
        times["check"].append(
            run_tests(
                driver, stock, checkout_a, target_a, driver_store, "check", nextest
            )
        )
        check_counters(is_artificer, "check", before, read_counters(driver_store))

        before = read_counters(driver_store)
        times["test"].append(
            run_tests(
                driver, stock, checkout_a, target_a, driver_store, "test", nextest
            )
        )
        check_counters(is_artificer, "test", before, read_counters(driver_store))

        before = read_counters(driver_store)
        times["test-warm"].append(
            run_tests(
                driver, stock, checkout_a, target_a, driver_store, "test", nextest
            )
        )
        check_counters(is_artificer, "test-warm", before, read_counters(driver_store))

        if nextest:
            before = read_counters(driver_store)
            times["nextest"].append(
                run_tests(
                    driver,
                    stock,
                    checkout_a,
                    target_a,
                    driver_store,
                    "nextest",
                    nextest,
                )
            )
            check_counters(is_artificer, "nextest", before, read_counters(driver_store))
            before = read_counters(driver_store)
            times["nextest-warm"].append(
                run_tests(
                    driver,
                    stock,
                    checkout_a,
                    target_a,
                    driver_store,
                    "nextest-warm",
                    nextest,
                )
            )
            check_counters(
                is_artificer, "nextest-warm", before, read_counters(driver_store)
            )

        edited = checkout_a / "crates" / mid_name / "src" / "lib.rs"
        text = edited.read_text().replace(
            f"pub const BASE: u64 = {mid};", f"pub const BASE: u64 = {mid + 1};"
        )
        edited.write_text(text)
        before = read_counters(driver_store)
        times["edit"].append(
            build_and_check(
                driver,
                checkout_a,
                target_a,
                driver_store,
                stock,
                expected_output(mid, top, mid + 1),
            )
        )
        check_counters(is_artificer, "edit", before, read_counters(driver_store))
        if not keep:
            shutil.rmtree(work, ignore_errors=True)
    return {case: values for case, values in times.items() if values}
